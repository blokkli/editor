import * as fs from 'node:fs'
import { createJiti } from 'jiti'
import { defineCodeTemplate } from '../../../../build/templates/defineTemplate'
import type { PrimitiveCollector, PrimitiveItem } from '../PrimitiveCollector'
import { getAllClasses } from '../../runtime/helpers'
import type {
  CompositionPrimitive,
  CompositionTokens,
} from '../../runtime/types'

/**
 * Writes every class a composition can render to a file, for the project's
 * Tailwind to pick up with `@source`. Only when the classes change, so that
 * Tailwind doesn't rebuild for nothing.
 */
async function writeSafelist(
  items: PrimitiveItem[],
  tokensPath: string | null,
  outPath: string,
  typesPath: string,
) {
  const jiti = createJiti(import.meta.url, {
    moduleCache: false,
    fsCache: false,
    alias: { '#blokkli/composition/types': typesPath },
  })
  const primitives: CompositionPrimitive[] = []
  for (const item of items) {
    primitives.push(
      await jiti.import<CompositionPrimitive>(item.definitionPath, {
        default: true,
      }),
    )
  }
  const tokens: CompositionTokens = tokensPath
    ? await jiti.import<CompositionTokens>(tokensPath, { default: true })
    : { breakpoints: {}, groups: {} }

  const content =
    '# Generated by the blökkli composition module: the classes compositions can render.\n' +
    getAllClasses(primitives, tokens).join('\n') +
    '\n'
  const existing = fs.existsSync(outPath)
    ? fs.readFileSync(outPath, 'utf8')
    : ''
  if (existing !== content) {
    fs.writeFileSync(outPath, content)
  }
}

export default function (
  collector: PrimitiveCollector,
  options: { safelistPath: string; typesPath: string },
) {
  return [
    // The definitions and the tokens: no Vue, the server imports them too
    // (the agent's tools).
    defineCodeTemplate(
      'composition-definitions',
      async (ctx) => {
        const rel = (p: string) =>
          ctx.helper.toModuleBuildRelative(p).replace(/\.ts$/, '')
        const items = collector.getItems()
        const tokensPath = collector.getTokensPath()

        try {
          await writeSafelist(
            items,
            tokensPath,
            options.safelistPath,
            options.typesPath,
          )
        } catch (e) {
          ctx.helper.logger.warn(
            'Could not write the composition safelist: ' + String(e),
          )
        }

        const imports = items.map(
          (it) =>
            `import ${it.importName}_definition from '${rel(it.definitionPath)}'`,
        )

        return `${imports.join('\n')}
${tokensPath ? `import tokensDefinition from '${rel(tokensPath)}'` : `const tokensDefinition = { breakpoints: {}, groups: {} }`}

export const primitives = {
${items.map((it) => `  '${it.id}': ${it.importName}_definition,`).join('\n')}
}

export const tokens = tokensDefinition
`
      },
      () => `import type { CompositionPrimitive, CompositionTokens } from '#blokkli/composition/types'

export const primitives: Record<string, CompositionPrimitive>
export const tokens: CompositionTokens
`,
      {
        dependencies: ['composition-primitives'],
        write: true,
        context: 'both',
      },
    ),
    defineCodeTemplate(
      'composition-components',
      (ctx) => {
        const items = collector.getItems()
        const imports = items.map(
          (it) =>
            `import ${it.importName}_component from '${ctx.helper.toModuleBuildRelative(it.renderPath)}'`,
        )
        return `${imports.join('\n')}

export const primitiveComponents = {
${items.map((it) => `  '${it.id}': ${it.importName}_component,`).join('\n')}
}
`
      },
      () => `import type { Component } from 'vue'

export const primitiveComponents: Record<string, Component>
`,
      { dependencies: ['composition-primitives'], write: true },
    ),
  ]
}
